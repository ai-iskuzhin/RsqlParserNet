namespace RsqlParserNet.Linq;

/// <summary>
/// Defines the direction for a sort expression.
/// </summary>
public enum RsqlSortDirection
{
    /// <summary>
    /// Sorts from the lowest value to the highest value.
    /// </summary>
    Ascending,

    /// <summary>
    /// Sorts from the highest value to the lowest value.
    /// </summary>
    Descending
}
